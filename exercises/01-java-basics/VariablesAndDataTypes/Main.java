public class Main {
    static void main(String[] args) {
        // Working with data types

        // Premative -- Store values in the stack
        // ---  int, double, float, boolean

        // Variables (Premative)

        // integer
        int stock = 12;
        int price = 30;
        int total = stock + price;
        System.out.println(total);

        // double
        double iphonePrice = 120.99;
        double totalPrice = iphonePrice * price;
        System.out.println(totalPrice);

        // boolean
        boolean isStudent = false;
        boolean isMarried = true;
        System.out.println(isStudent);

        // Reference -- Store reference of the stack value in the heap
        // -- string, arrays, objects







    }
}



